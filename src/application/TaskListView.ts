import type { TaskDto } from "./TaskDto";

/**
 * タスク一覧の画面が表示に必要とするものの一式。
 *
 * 画面は「全件の一覧」を持っていても、そのまま描くわけではない。
 * 表示するのは選択中のフィルタで絞り込んだ一覧と、未完了の件数である。
 * その組み立てを UI に散らさず、ひとつの型として application 層が示す。
 *
 * ドメインモデルではなく DTO で構成されているのは、これが「画面に何を出すか」
 * という UI の関心事だから。画面の都合で項目が増えても、ドメインモデルは変わらない。
 */
export type TaskListView = {
  /** 選択中のフィルタで絞り込んだ、実際に並べる Task */
  visibleTasks: TaskDto[];
  /** 未完了の件数。フィルタの選択状態とは無関係 */
  remainingCount: number;
};
